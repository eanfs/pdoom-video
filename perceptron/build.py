#!/usr/bin/env python3
"""Build the 03-01 perceptron explainer: cues.ts, engine data JSON, SRT.

Scene structure follows the parent-repo production plan (Task 10, 12 scenes);
captions distill phases/03-deep-learning-core/01-the-perceptron/docs/zh.md.
All numeric results shown on screen come from actually running
phases/03-deep-learning-core/01-the-perceptron/code/perceptron.py
(course-run.txt in this directory keeps the raw output).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROD = 'perceptron'
FPS = 30
PER_CHAR = 0.23      # silent reading pace, seconds per CJK glyph
MIN_LINE = 3.0
LEAD, TAIL, GAP = 1.8, 1.2, 0.5

SCENES = [
 dict(id='intro', title='感知机', lines=[
  '你懂点积和矩阵，但机器怎么学会该用哪种变换？',
  '感知机是最简单的学习机器：加权、求和、决策，然后调整。',
  '每一个神经网络，都是把这个想法一层层叠起来的产物。']),
 dict(id='neuron', title='01 / 一个神经元，一个决策', lines=[
  '感知机接收 n 个输入，每个乘上一个权重。',
  '全部加起来，再补上一个偏置。',
  '送进激活函数，输出 0 或 1——这就是一次决策。']),
 dict(id='weighted', title='02 / 加权求和，再加一个偏置', lines=[
  'AND 门实测：第 4 轮收敛。',
  '权重 w = [0.2, 0.1]，偏置 b = -0.2。',
  '权重缩放每个输入的贡献，偏置平移判断的门槛。']),
 dict(id='step', title='03 / 阶跃函数：压成 0 或 1', lines=[
  '加权和加偏置大于等于 0，就输出 1；否则输出 0。',
  '没有中间状态，决策干净利落。',
  '它不可导——为后面换 sigmoid 埋下伏笔。']),
 dict(id='boundary', title='04 / 决策边界就是一条直线', lines=[
  '两个输入时，感知机在平面上画出一条直线。',
  'w1·x1 + w2·x2 + b = 0 就是这条边界。',
  '一侧全 0、一侧全 1；训练就是挪这条线。']),
 dict(id='rule', title='05 / 学习规则：错了就往回推', lines=[
  '预测正确，误差为 0，什么都不动。',
  '预测成 0 但应为 1，权重增大；方向反了就减小。',
  'w += lr · error · x——学习就是不断调整数字。']),
 dict(id='or', title='06 / 训练一个 OR 门', lines=[
  'OR 门实测：第 4 轮收敛，四个输入全对。',
  '学到的权重 [0.1, 0.1]，偏置 -0.1。',
  'AND、NOT 同样几轮收敛——线性可分问题手到擒来。']),
 dict(id='xor', title='07 / XOR：单层网络的死穴', lines=[
  'XOR 的四个点，任何一条直线都分不开。',
  '实测：训练 1000 轮不收敛，两例预测错误。',
  '1969 年 Minsky 证明此限制，研究几乎停滞十年。']),
 dict(id='hidden', title='08 / 加一层隐藏层', lines=[
  '诀窍：XOR = (x1 OR x2) AND NOT (x1 AND x2)。',
  '三个感知机组两层，权重手工设好。',
  '实测四种输入全部正确——直线叠出曲线。']),
 dict(id='sigmoid', title='09 / 换 sigmoid，让它自己学', lines=[
  '阶跃换成 sigmoid，梯度存在，误差可反向传播。',
  '实测总误差从 1.2164 一路降到 0.0003。',
  '输出 0.0074 / 0.9923 / 0.9923 / 0.0094，四种全对。']),
 dict(id='code', title='10 / 把整条流程写成 Python', lines=[
  '核心只有三十行：predict 与 train 两个方法。',
  '预测是点积加偏置过阶跃；训练按误差调权重。',
  'sklearn 的 Perceptron 做同一件事，差距在规模。']),
 dict(id='recap', title='一张白板，一个感知机', lines=[
  '输入 → 加权求和 → 激活 → 决策。',
  '单个感知机只能画直线，叠起来才能画任意形状。',
  '权重、偏置、线性可分、多层——这门课的地基。']),
]

def build():
    cues, t = [], 0.0
    for sc in SCENES:
        times, cur = [], LEAD
        for ln in sc['lines']:
            d = max(MIN_LINE, len(ln) * PER_CHAR)
            times.append(round(cur, 2)); cur += d + GAP
        dur = cur - GAP + TAIL
        cues.append(dict(id=sc['id'], start=round(t, 2), end=round(t + dur, 2),
                         title=sc['title'], caption=sc['lines'], lt=times))
        t += dur
    total = round(t, 2)

    def j(o): return json.dumps(o, ensure_ascii=False)
    scenes_ts = ',\n'.join(
        '  {\n    "id": ' + j(s["id"]) + ',\n    "start": ' + str(s["start"]) + ',\n    "end": ' + str(s["end"]) + ',\n'
        '    "title": ' + j(s["title"]) + ',\n    "caption": ' + j(s["caption"]) + ',\n    "lt": ' + j(s["lt"]) + '\n  }'
        for s in cues)
    (ROOT / f'app/src/{PROD}/cues.ts').write_text(
        '// Generated by ' + PROD + '/build.py — the single source of time for this video.\n'
        'export const FPS = ' + str(FPS) + ';\nexport const DURATION = ' + str(total) + ';\n'
        'export const SCENES = [\n' + scenes_ts + '\n];\n', encoding='utf-8')

    beats = list(range(int(total) + 1))
    downbeats = beats[::4]
    (ROOT / f'data/{PROD}.json').write_text(json.dumps(dict(
        duration=total, bpm=60, fps=FPS, beats=beats, downbeats=downbeats,
        sections=[dict(name=s['id'], start=s['start'], end=s['end']) for s in cues],
        features={}, onsets={}), ensure_ascii=False) + '\n', encoding='utf-8')
    (ROOT / f'data/{PROD}-lyrics.json').write_text('{"lines":[]}\n', encoding='utf-8')

    def stamp(v):
        ms = round(v * 1000)
        return f'{ms//3600000:02}:{ms//60000%60:02}:{ms//1000%60:02},{ms%1000:03}'
    srt, n = [], 0
    for s in cues:
        for i, ln in enumerate(s['caption']):
            a = s['start'] + s['lt'][i]
            b = s['end'] - (TAIL - 0.2) if i == len(s['caption']) - 1 else s['start'] + s['lt'][i + 1] - GAP
            n += 1
            srt.append(f'{n}\n{stamp(a)} --> {stamp(b)}\n{ln}\n')
    (ROOT / f'{PROD}/{PROD}.srt').write_text('\n'.join(srt), encoding='utf-8')
    print(json.dumps(dict(prod=PROD, duration=total, scenes=len(cues), frames=round(total * FPS))))

if __name__ == '__main__':
    build()
