_MANIFEST = None

def _measured(sid, i, ln):
    """Real TTS clip duration when the manifest line matches, else the reading estimate."""
    global _MANIFEST
    if _MANIFEST is None:
        import json as _json
        from pathlib import Path as _P
        _p = _P(__file__).resolve().parent / 'tts-manifest.json'
        _MANIFEST = _json.loads(_p.read_text(encoding='utf-8')) if _p.exists() else {'scenes': {}}
    m = _MANIFEST['scenes'].get(sid)
    if m and i < len(m) and m[i]['text'] == ln:
        return m[i]['dur']
    return max(MIN_LINE, len(ln) * PER_CHAR)

def build():
    cues, t = [], 0.0
    for sc in SCENES:
        times, cur = [], LEAD
        for i, ln in enumerate(sc['lines']):
            d = _measured(sc['id'], i, ln)
            times.append(round(cur, 2)); cur += d + GAP
        dur = cur - GAP + TAIL
        cues.append(dict(id=sc['id'], start=round(t, 2), end=round(t + dur, 2),
                         title=sc['title'], caption=sc['lines'], lt=times))
        t += dur
    total = round(t, 2)

    def j(o): return json.dumps(o, ensure_ascii=False)
    scenes_ts = ',\n'.join(
        '  {\n    "id": ' + j(s["id"]) + ',\n    "start": ' + str(s["start"]) + ',\n    "end": ' + str(s["end"]) + ',\n'
        '    "title": ' + j(s["title"]) + ',\n    "caption": ' + j(s["caption"]) + ',\n    "lt": ' + j(s["lt"]) + '\n  }'
        for s in cues)
    (ROOT / f'app/src/{PROD}/cues.ts').write_text(
        '// Generated by ' + PROD + '/build.py — the single source of time for this video.\n'
        'export const FPS = ' + str(FPS) + ';\nexport const DURATION = ' + str(total) + ';\n'
        'export const SCENES = [\n' + scenes_ts + '\n];\n', encoding='utf-8')

    beats = list(range(int(total) + 1))
    (ROOT / f'data/{PROD}.json').write_text(json.dumps(dict(
        duration=total, bpm=60, fps=FPS, beats=beats, downbeats=beats[::4],
        sections=[dict(name=s['id'], start=s['start'], end=s['end']) for s in cues],
        features={}, onsets={}), ensure_ascii=False) + '\n', encoding='utf-8')
    (ROOT / f'data/{PROD}-lyrics.json').write_text('{"lines":[]}\n', encoding='utf-8')

    def stamp(v):
        ms = round(v * 1000)
        return f'{ms//3600000:02}:{ms//60000%60:02}:{ms//1000%60:02},{ms%1000:03}'
    srt, n = [], 0
    for s in cues:
        for i, ln in enumerate(s['caption']):
            a = s['start'] + s['lt'][i]
            b = s['end'] - (TAIL - 0.2) if i == len(s['caption']) - 1 else s['start'] + s['lt'][i + 1] - GAP
            n += 1
            srt.append(f'{n}\n{stamp(a)} --> {stamp(b)}\n{ln}\n')
    (ROOT / f'{PROD}/{PROD}.srt').write_text('\n'.join(srt), encoding='utf-8')
    print(json.dumps(dict(prod=PROD, duration=total, scenes=len(cues), frames=round(total * FPS))))

if __name__ == '__main__':
    build()
