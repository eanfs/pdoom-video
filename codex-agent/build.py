#!/usr/bin/env python3
"""Rebuild the 14-01 agent-loop explainer to the plan's 9-scene T-M structure.

Captions distill phases/14-agent-engineering/01-the-agent-loop/docs/zh.md;
numbers (120 × 0.15 = 18, total 138) come from that lesson's code/main.py run
(course-run.txt keeps the raw output). Silent, reading-paced.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROD = 'codex-agent'
FPS = 30
PER_CHAR = 0.27
MIN_LINE = 3.0
LEAD, TAIL, GAP = 1.2, 2.0, 1.6

SCENES = [
 dict(id='intro', title='Agent 循环', lines=[
  '一次问答给一个答案；一次任务要很多步。',
  '完成任务靠一个循环：观察、决策、执行、回流。',
  '本集拆开这个最小可用的 Agent 循环。']),
 dict(id='loop', title='01 / 观察 → 思考 → 行动', lines=[
  '先把目标和已有结果放进上下文。',
  '模型提出下一步：调工具，或宣布完成。',
  '结果写回历史，进入下一轮——循环闭合。']),
 dict(id='react', title='02 / ReAct：标准格式', lines=[
  'ReAct 用三段式记录循环：Thought、Action、Observation。',
  '思考写明理由；行动给出工具名与参数。',
  '观察记录真实执行结果，供下一轮引用。']),
 dict(id='native', title='03 / 2026 年的转变：原生推理', lines=[
  '推理模型把思考内化进了模型本身。',
  '格式不再显式分三段，但循环没有消失。',
  '工具调用、结果回流、停止判断，一步不少。']),
 dict(id='five', title='04 / 五大要素', lines=[
  '模型提供决策；工具扩展能力。',
  '记忆保存状态；宿主程序执行并把关。',
  '停止条件防止无限循环——缺一不可。']),
 dict(id='tools', title='05 / 工具是循环的手', lines=[
  '模型请求：action 是 calculator，args 是 120 * 0.15。',
  '宿主检查名称与参数，再在本地执行。',
  '税额 18——结果来自程序，不是模型幻觉。']),
 dict(id='everywhere', title='06 / 为什么这个循环无处不在', lines=[
  '写代码、查资料、订机票，骨架都是同一个循环。',
  '换的只是工具集与停止条件。',
  '理解一个循环，就理解了大多数 Agent。']),
 dict(id='pitfalls', title='07 / 2026 年的坑', lines=[
  '把工具失败当成任务失败——该重试或换路。',
  '不设轮数上限，模型原地打转烧掉预算。',
  '把整个网页塞进上下文，挤掉真正重要的信息。']),
 dict(id='recap', title='一屏总览：一个 Agent 循环', lines=[
  '观察、决策、执行、回流，然后明确停止。',
  '课程实测：两次工具调用，总价 138。',
  '先把最小循环跑通，再扩展复杂能力。']),
]

_MANIFEST = None

def _measured(sid, i, ln):
    """Real TTS clip duration when the manifest line matches, else the reading estimate."""
    global _MANIFEST
    if _MANIFEST is None:
        import json as _json
        from pathlib import Path as _P
        _p = _P(__file__).resolve().parent / 'tts-manifest.json'
        _MANIFEST = _json.loads(_p.read_text(encoding='utf-8')) if _p.exists() else {'scenes': {}}
    m = _MANIFEST['scenes'].get(sid)
    if m and i < len(m) and m[i]['text'] == ln:
        return m[i]['dur']
    return max(MIN_LINE, len(ln) * PER_CHAR)

def build():
    cues, t = [], 0.0
    for sc in SCENES:
        times, cur = [], LEAD
        for i, ln in enumerate(sc['lines']):
            d = _measured(sc['id'], i, ln)
            times.append(round(cur, 2)); cur += d + GAP
        dur = cur - GAP + TAIL
        cues.append(dict(id=sc['id'], start=round(t, 2), end=round(t + dur, 2),
                         title=sc['title'], caption=sc['lines'], lt=times))
        t += dur
    total = round(t, 2)

    def j(o): return json.dumps(o, ensure_ascii=False)
    scenes_ts = ',\n'.join(
        '  {\n    "id": ' + j(s["id"]) + ',\n    "start": ' + str(s["start"]) + ',\n    "end": ' + str(s["end"]) + ',\n'
        '    "title": ' + j(s["title"]) + ',\n    "caption": ' + j(s["caption"]) + ',\n    "lt": ' + j(s["lt"]) + '\n  }'
        for s in cues)
    (ROOT / f'app/src/{PROD}/cues.ts').write_text(
        '// Generated by ' + PROD + '/build.py — the single source of time for this video.\n'
        'export const FPS = ' + str(FPS) + ';\nexport const DURATION = ' + str(total) + ';\n'
        'export const SCENES = [\n' + scenes_ts + '\n];\n', encoding='utf-8')

    beats = list(range(int(total) + 1))
    (ROOT / f'data/{PROD}.json').write_text(json.dumps(dict(
        duration=total, bpm=60, fps=FPS, beats=beats, downbeats=beats[::4],
        sections=[dict(name=s['id'], start=s['start'], end=s['end']) for s in cues],
        features={}, onsets={}), ensure_ascii=False) + '\n', encoding='utf-8')
    (ROOT / f'data/{PROD}-lyrics.json').write_text('{"lines":[]}\n', encoding='utf-8')

    def stamp(v):
        ms = round(v * 1000)
        return f'{ms//3600000:02}:{ms//60000%60:02}:{ms//1000%60:02},{ms%1000:03}'
    srt, n = [], 0
    for s in cues:
        for i, ln in enumerate(s['caption']):
            a = s['start'] + s['lt'][i]
            b = s['end'] - (TAIL - 0.2) if i == len(s['caption']) - 1 else s['start'] + s['lt'][i + 1] - GAP
            n += 1
            srt.append(f'{n}\n{stamp(a)} --> {stamp(b)}\n{ln}\n')
    (ROOT / f'{PROD}/agent-loop.srt').write_text('\n'.join(srt), encoding='utf-8')
    print(json.dumps(dict(prod=PROD, duration=total, scenes=len(cues), frames=round(total * FPS))))

if __name__ == '__main__':
    build()
