#!/usr/bin/env python3
"""Build the 07-01 why-transformers explainer: cues.ts, engine data JSON, SRT.

Scene structure follows the parent-repo production plan (Task 11, 12 scenes);
captions distill phases/07-transformers-deep-dive/01-why-transformers/docs/zh.md.
Numeric results come from actually running that lesson's code/main.py
(course-run.txt keeps the raw output).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROD = 'why-transformers'
FPS = 30
PER_CHAR = 0.23
MIN_LINE = 3.0
LEAD, TAIL, GAP = 1.8, 1.2, 0.5

SCENES = [
 dict(id='intro', title='为什么需要 Transformer', lines=[
  '2017 年之前，最先进的序列模型都是循环神经网络。',
  'Transformer 一次看全部 token；RNN 一次只能看一个。',
  '这个架构赌注，改写了之后的每一条 scaling 曲线。']),
 dict(id='rnn', title='01 / RNN：一步一步传递状态', lines=[
  'RNN 计算 h_t = f(h_t−1, x_t)，每步依赖上一步。',
  '算不出 h_4，就没法算 h_5——时间轴上强制串行。',
  '在上万核心的 GPU 上，长序列浪费掉绝大多数算力。']),
 dict(id='depth', title='02 / 串行深度：N 步不能并行', lines=[
  '决定墙钟时间的是依赖深度，不是运算总数。',
  'RNN 的串行深度是 N：序列多长，链就有多长。',
  '注意力的深度是 log N 甚至 1——差距是量级的。']),
 dict(id='measure', title='03 / 第 1 步：测量串行深度', lines=[
  '实测：N = 64 时，并行归约有 11 倍优势。',
  'N = 4096 时 341 倍；N = 262144 时 14564 倍。',
  '数学一样，依赖图不同，差距随长度爆炸。']),
 dict(id='ops', title='04 / 第 2 步：数一数理论运算量', lines=[
  '两个算法都做 N 次加法，运算量相同。',
  '但 RNN 深度是 N，注意力树形归约是 log N。',
  'GPU 时间由深度决定——这正是硬件的脾气。']),
 dict(id='wallclock', title='05 / 第 3 步：长序列实测', lines=[
  '纯 Python 实测：百万元素，串行 10.50 毫秒。',
  '归约版 1.63 毫秒，稳定约 6.4 倍。',
  '前缀和校验 0 处不一致——快，而且结果相同。']),
 dict(id='bottleneck', title='06 / 状态是瓶颈', lines=[
  '编码器要把整个源序列挤进一个固定宽度向量。',
  '5 个 token 和 500 个 token，瓶颈一样大。',
  '解码器只看得到这个向量——信息被迫断崖。']),
 dict(id='longrange', title='07 / 长程依赖要走很远的路', lines=[
  '50 个 token 之前的信息，要经过 50 层非线性。',
  '门控缓解了梯度消失，但从未消除它。',
  '「去年夏天在飞机上读的那本书」——经常就断了。']),
 dict(id='attention', title='08 / 注意力：一次看到整段', lines=[
  '让每个位置并行关注其他所有位置。',
  'N×N 注意力矩阵，一次批量 matmul 填满。',
  '没有哪一步依赖另一步——GPU 最喜欢这个。']),
 dict(id='cost', title='09 / 代价：注意力是 O(N²)', lines=[
  '注意力显存按 N² 增长：2K 没问题，128K 要分块。',
  'RNN 时间显存都 O(N)；Transformer 拿时间换显存。',
  '再靠并行把时间赚回来——是权衡，不是免费午餐。']),
 dict(id='code', title='10 / 用代码量一遍', lines=[
  'rnn_style 是一条加法链，无法并行。',
  'attention_style 是求平均，每个元素独立。',
  '十几行代码，就能在笔记本上量出这个差距。']),
 dict(id='recap', title='一张白板，从 RNN 到注意力', lines=[
  '串行链换成广播矩阵，深度 N 变成深度 1。',
  '代价是 O(N²) 显存，换来全面的并行。',
  '循环没死：Mamba 把它变成混合模型的组件。']),
]

def build():
    cues, t = [], 0.0
    for sc in SCENES:
        times, cur = [], LEAD
        for ln in sc['lines']:
            d = max(MIN_LINE, len(ln) * PER_CHAR)
            times.append(round(cur, 2)); cur += d + GAP
        dur = cur - GAP + TAIL
        cues.append(dict(id=sc['id'], start=round(t, 2), end=round(t + dur, 2),
                         title=sc['title'], caption=sc['lines'], lt=times))
        t += dur
    total = round(t, 2)

    def j(o): return json.dumps(o, ensure_ascii=False)
    scenes_ts = ',\n'.join(
        '  {\n    "id": ' + j(s["id"]) + ',\n    "start": ' + str(s["start"]) + ',\n    "end": ' + str(s["end"]) + ',\n'
        '    "title": ' + j(s["title"]) + ',\n    "caption": ' + j(s["caption"]) + ',\n    "lt": ' + j(s["lt"]) + '\n  }'
        for s in cues)
    (ROOT / f'app/src/{PROD}/cues.ts').write_text(
        '// Generated by ' + PROD + '/build.py — the single source of time for this video.\n'
        'export const FPS = ' + str(FPS) + ';\nexport const DURATION = ' + str(total) + ';\n'
        'export const SCENES = [\n' + scenes_ts + '\n];\n', encoding='utf-8')

    beats = list(range(int(total) + 1))
    (ROOT / f'data/{PROD}.json').write_text(json.dumps(dict(
        duration=total, bpm=60, fps=FPS, beats=beats, downbeats=beats[::4],
        sections=[dict(name=s['id'], start=s['start'], end=s['end']) for s in cues],
        features={}, onsets={}), ensure_ascii=False) + '\n', encoding='utf-8')
    (ROOT / f'data/{PROD}-lyrics.json').write_text('{"lines":[]}\n', encoding='utf-8')

    def stamp(v):
        ms = round(v * 1000)
        return f'{ms//3600000:02}:{ms//60000%60:02}:{ms//1000%60:02},{ms%1000:03}'
    srt, n = [], 0
    for s in cues:
        for i, ln in enumerate(s['caption']):
            a = s['start'] + s['lt'][i]
            b = s['end'] - (TAIL - 0.2) if i == len(s['caption']) - 1 else s['start'] + s['lt'][i + 1] - GAP
            n += 1
            srt.append(f'{n}\n{stamp(a)} --> {stamp(b)}\n{ln}\n')
    (ROOT / f'{PROD}/{PROD}.srt').write_text('\n'.join(srt), encoding='utf-8')
    print(json.dumps(dict(prod=PROD, duration=total, scenes=len(cues), frames=round(total * FPS))))

if __name__ == '__main__':
    build()
